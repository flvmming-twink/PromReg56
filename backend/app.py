@app.get("/api/companies")
def companies():
    query = request.args.get("search", "").strip()
    sort = request.args.get("sort", "")
    order = "revenue DESC NULLS LAST, e.name" if sort == "revenue_desc" else "revenue ASC NULLS LAST, e.name" if sort == "revenue_asc" else "e.id"
    sql = f"""
            SELECT e.id, e.name, i.name AS industry, c.name AS city,
                   CASE WHEN e.status = 'Инвестиционный проект' THEN 'В стадии проекта'
                        ELSE COALESCE(e.status, 'Действующее') END AS status,
                   COALESCE(metrics.employees, 0)::integer AS workers,
                   COALESCE(ROUND(metrics.revenue / 1000000), 0)::bigint AS revenue,
                   COALESCE(e.latitude, c.latitude) AS latitude,
                   COALESCE(e.longitude, c.longitude) AS longitude,
                   e.website, e.activity_description, e.products
            FROM public.enterprises e
            JOIN public.cities c ON c.id = e.city_id
            JOIN public.industries i ON i.id = e.industry_id
            LEFT JOIN LATERAL (
                SELECT employees, revenue
                FROM public.enterprise_metrics
                WHERE enterprise_id = e.id
                ORDER BY year DESC
                LIMIT 1
            ) metrics ON TRUE
    """
    parameters = ()
    if query:
        sql += " WHERE e.name ILIKE %s"
        parameters = (f"%{query}%",)
    with get_connection() as connection:
        rows = connection.execute(f"{sql} ORDER BY {order}", parameters).fetchall()
    return jsonify(rows)


@app.get("/api/analytics")
def analytics():
    territory = request.args.get("territory", "").strip()
    period = request.args.get("period", "2021-2025").strip()
    metric = request.args.get("metric", "revenue").strip()
    metrics = {
        "revenue": "revenue",
        "employees": "employees",
        "investments": "investments",
    }
    if metric not in metrics:
        return jsonify({"error": "Выберите выручку, занятость или инвестиции"}), 400

    period_parts = period.split("-")
    if len(period_parts) not in (1, 2) or any(not part.isdecimal() for part in period_parts):
        return jsonify({"error": "Укажите период в формате ГГГГ или ГГГГ-ГГГГ"}), 400
    start_year = int(period_parts[0])
    end_year = int(period_parts[-1])
    if (
        start_year < 2000
        or end_year > 2100
        or start_year > end_year
        or end_year - start_year > 10
    ):
        return jsonify({"error": "Выбран некорректный период"}), 400

    try:
        with get_connection() as connection:
            cities = connection.execute(
                "SELECT id, name FROM public.cities ORDER BY name"
            ).fetchall()
            industries = connection.execute(
                "SELECT id, name FROM public.industries ORDER BY name"
            ).fetchall()
            if territory and not any(city["name"] == territory for city in cities):
                return jsonify({"error": "Выбранная территория не найдена"}), 400

            rows = connection.execute(
                """SELECT e.id, e.name, e.status, c.id AS city_id, c.name AS city,
                          i.id AS industry_id, i.name AS industry, m.year,
                          m.employees, m.revenue::double precision AS revenue,
                          m.investments::double precision AS investments
                   FROM public.enterprises e
                   JOIN public.cities c ON c.id = e.city_id
                   JOIN public.industries i ON i.id = e.industry_id
                   LEFT JOIN public.enterprise_metrics m
                     ON m.enterprise_id = e.id AND m.year BETWEEN %s AND %s
                   ORDER BY e.name, m.year""",
                (start_year, end_year),
            ).fetchall()
    except psycopg.OperationalError:
        app.logger.exception("Не удалось подключить базу для аналитической панели")
        return jsonify({
            "error": "Не удалось загрузить аналитику: PostgreSQL недоступен. Проверьте подключение и повторите запрос."
        }), 503

    companies_by_id = {}
    for row in rows:
        company = companies_by_id.setdefault(row["id"], {
            "id": row["id"],
            "name": row["name"],
            "status": row["status"] or "",
            "city_id": row["city_id"],
            "city": row["city"],
            "industry_id": row["industry_id"],
            "industry": row["industry"],
            "years": {},
        })
        if row["year"] is not None:
            company["years"][row["year"]] = {
                "employees": row["employees"],
                "revenue": row["revenue"],
                "investments": row["investments"],
            }

    def metric_value(values):
        value = values.get(metrics[metric])
        if value is None:
            return None
        return float(value) / 1_000_000_000 if metric in ("revenue", "investments") else int(value)

    selected_companies = {
        company_id: company for company_id, company in companies_by_id.items()
        if not territory or company["city"] == territory
    }
    available_years = sorted({
        year
        for company in selected_companies.values()
        for year, values in company["years"].items()
        if values.get(metrics[metric]) is not None
    })
    current_year = max(available_years) if available_years else end_year

    def snapshot_company(company):
        values = company["years"].get(current_year, {})
        return {
            **{key: value for key, value in company.items() if key != "years"},
            "employees": int(values["employees"]) if values.get("employees") is not None else None,
            "revenue": float(values["revenue"]) / 1_000_000_000 if values.get("revenue") is not None else None,
            "investments": float(values["investments"]) / 1_000_000_000 if values.get("investments") is not None else None,
            "value": metric_value(values) or 0,
        }

    all_current_companies = [
        snapshot_company(company) for company in companies_by_id.values()
    ]
    current_companies = [
        snapshot_company(company) for company in selected_companies.values()
    ]

    metric_totals = {}
    for year in available_years:
        year_values = [
            company["years"][year]
            for company in selected_companies.values()
            if year in company["years"]
        ]
        populated_values = [metric_value(values) for values in year_values]
        populated_values = [value for value in populated_values if value is not None]
        if populated_values:
            metric_totals[year] = sum(populated_values)

    def aggregate_by(key_name, companies_to_aggregate):
        groups = {}
        for company in companies_to_aggregate:
            key = company[key_name]
            group = groups.setdefault(key, {
                "name": company["industry"] if key_name == "industry_id" else company["city"],
                "companies": 0,
                "employees": 0,
                "revenue": 0.0,
                "investments": 0.0,
                "value": 0.0,
            })
            group["companies"] += 1
            group["employees"] += company["employees"] or 0
            group["revenue"] += company["revenue"] or 0
            group["investments"] += company["investments"] or 0
            group["value"] += company["value"]
        return sorted(groups.values(), key=lambda group: group["value"], reverse=True)

    territory_totals = aggregate_by("city_id", all_current_companies)

    value_unit = "чел." if metric == "employees" else "млрд ₽"
    total_value = sum(company["value"] for company in current_companies)
    period_years = [
        {"year": year, "value": metric_totals.get(year)}
        for year in range(start_year, end_year + 1)
        if year in metric_totals
    ]
    current_companies.sort(key=lambda company: company["value"], reverse=True)
    return jsonify({
        "filters": {
            "territory": territory or "",
            "period": period,
            "metric": metric,
        },
        "current_year": current_year,
        "value_unit": value_unit,
        "kpis": {
            "companies": len(current_companies),
            "employees": (
                sum(company["employees"] or 0 for company in current_companies)
                if any(company["employees"] is not None for company in current_companies)
                else None
            ),
            "metric_total": total_value if available_years else None,
            "investment_projects": sum(
                company["status"] in ("Инвестиционный проект", "В стадии проекта")
                for company in current_companies
            ),
        },
        "series": period_years,
        "top_enterprises": current_companies[:10],
        "industries": aggregate_by("industry_id", current_companies),
        "territories": sorted(territory_totals, key=lambda group: group["value"], reverse=True),
        "companies": current_companies,
        "cities": cities,
        "industry_options": industries,
    })


