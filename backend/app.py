def report_rows(connection, report_type, period):
    year = int(period[:4])
    if report_type == "Реестр предприятий":
        query = """
            SELECT e.name AS "Предприятие", i.name AS "Отрасль", c.name AS "Город",
                   e.status AS "Статус", metrics.year AS "Год",
                   metrics.employees AS "Работники", metrics.revenue AS "Выручка, ₽"
            FROM public.enterprises e
            JOIN public.cities c ON c.id = e.city_id
            JOIN public.industries i ON i.id = e.industry_id
            LEFT JOIN public.enterprise_metrics metrics ON metrics.enterprise_id = e.id
                AND metrics.year BETWEEN %s AND %s
            ORDER BY e.name, metrics.year
        """
        parameters = (2021 if "–" in period else year, year if "–" in period else year)
    elif report_type == "Инвестиционные проекты":
        query = """
            SELECT e.name AS "Предприятие", i.name AS "Отрасль", c.name AS "Город",
                   e.status AS "Статус", metrics.year AS "Год",
                   metrics.employees AS "Работники", metrics.revenue AS "Выручка, ₽"
            FROM public.enterprises e
            JOIN public.cities c ON c.id = e.city_id
            JOIN public.industries i ON i.id = e.industry_id
            LEFT JOIN public.enterprise_metrics metrics ON metrics.enterprise_id = e.id
                AND metrics.year BETWEEN %s AND %s
            WHERE e.status IN ('Инвестиционный проект', 'В стадии проекта')
            ORDER BY e.name, metrics.year
        """
        parameters = (2021 if "–" in period else year, year if "–" in period else year)
    elif report_type == "Показатели территорий":
        query = """
            SELECT c.name AS "Территория", tm.year AS "Год",
                   tm.population AS "Население",
                   tm.average_salary AS "Средняя зарплата, ₽",
                   tm.unemployment_rate AS "Безработица, %",
                   tm.investments AS "Инвестиции, ₽",
                   tm.industrial_output AS "Промышленный выпуск, ₽",
                   tm.employed_population AS "Занятое население"
            FROM public.territory_metrics tm
            LEFT JOIN public.cities c ON c.id = tm.city_id
            WHERE tm.year BETWEEN %s AND %s
            ORDER BY tm.year, c.name
        """
        parameters = (2021 if "–" in period else year, year if "–" in period else year)
    else:
        query = """
            SELECT i.name AS "Отрасль", metrics.year AS "Год",
                   COUNT(DISTINCT e.id) AS "Предприятий",
                   SUM(metrics.employees) AS "Работники",
                   SUM(metrics.revenue) AS "Выручка, ₽"
            FROM public.industries i
            LEFT JOIN public.enterprises e ON e.industry_id = i.id
            LEFT JOIN public.enterprise_metrics metrics ON metrics.enterprise_id = e.id
                AND metrics.year BETWEEN %s AND %s
            GROUP BY i.id, i.name, metrics.year
            ORDER BY i.name, metrics.year
        """
        parameters = (2021 if "–" in period else year, year if "–" in period else year)
    return connection.execute(query, parameters).fetchall()


def create_report_workbook(report_type, period, author, created_at, rows):
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "Отчёт"
    sheet.append(["Отчёт", report_type])
    sheet.append(["Период", period])
    sheet.append(["Сформировал", author])
    sheet.append(["Дата формирования", created_at.strftime("%d.%m.%Y %H:%M")])
    sheet.append([])
    if rows:
        headers = list(rows[0].keys())
        sheet.append(headers)
        for row in rows:
            values = []
            for header in headers:
                value = row[header]
                if isinstance(value, str) and value.startswith(("=", "+", "-", "@")):
                    value = "'" + value
                values.append(value)
            sheet.append(values)
        for column in sheet.columns:
            max_length = max(len(str(cell.value or "")) for cell in column)
            sheet.column_dimensions[column[0].column_letter].width = min(max_length + 2, 45)
        sheet.freeze_panes = "A7"
        sheet.auto_filter.ref = sheet.dimensions
    else:
        sheet.append(["За выбранный период данных нет"])
    output = BytesIO()
    workbook.save(output)
    return output.getvalue()


