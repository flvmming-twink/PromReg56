@app.post("/api/reports")
@admin_required
def create_report():
    payload = request.get_json(silent=True) or {}
    report_type = str(payload.get("type", "")).strip()
    period = str(payload.get("period", "")).strip()
    note = str(payload.get("note", "")).strip()
    if report_type not in REPORT_TYPES or period not in REPORT_PERIODS:
        return jsonify({"error": "Выберите тип отчёта и период из списка"}), 400
    if len(note) > 200:
        return jsonify({"error": "Комментарий не должен превышать 200 символов"}), 400

    author = session.get("login", ADMIN_LOGIN)
    created_at = datetime.now().astimezone()
    name = note or f"{report_type} · {period}"
    with get_connection() as connection:
        ensure_generated_reports(connection)
        rows = report_rows(connection, report_type, period)
        file_data = create_report_workbook(report_type, period, author, created_at, rows)
        report = connection.execute(
            """INSERT INTO public.generated_reports
                   (name, report_type, period, author, created_at, file_data)
               VALUES (%s, %s, %s, %s, %s, %s)
               RETURNING id, name, report_type AS type, period, author,
                         created_at, octet_length(file_data) AS size""",
            (name, report_type, period, author, created_at, file_data),
        ).fetchone()
    return jsonify(report), 201


