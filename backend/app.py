@app.post("/api/sources")
@admin_required
def add_source():
    payload = request.get_json(silent=True) or {}
    name = str(payload.get("name", "")).strip()
    url = str(payload.get("url", "")).strip()
    source_type = str(payload.get("source_type", "")).strip()
    parsed_url = urlparse(url)
    if not name or not source_type or parsed_url.scheme not in ("http", "https") or not parsed_url.netloc:
        return jsonify({"error": "Укажите название, тип и корректный URL источника (http или https)"}), 400
    description = str(payload.get("description", "")).strip()
    with get_connection() as connection:
        row = connection.execute(
            """INSERT INTO public.data_sources (name, url, source_type, access_date, description)
               VALUES (%s, %s, %s, CURRENT_DATE, %s)
               RETURNING id, name, url, source_type, publication_date, access_date, description""",
            (name, url, source_type, description),
        ).fetchone()
    return jsonify(dict(row)), 201


